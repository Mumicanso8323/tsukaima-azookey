#!/usr/bin/env python3
"""Generate NaginataTable.swift from the Naginata v18 data.

Naginata v18 per eswai/zmk-naginata (reference table; keymap draft
/data/ashwell/life/keyboard-layouts/scoring/keymaps/naginata_corne/BUILD.md;
revision pin 6d852bf9b4). Source JSON = behavior_naginata.c ngdickana[] kana entries.
NOT independently verified against the official site.
usage: gen_naginata_table.py naginata_v18.json > NaginataTable.swift
"""
import json, sys
d = json.load(open(sys.argv[1]))['kana']
symbols = {  # J+K+x chords from naginata_func.c
    'd': '？', 'f': '「', 'v': '」', 'c': '！', 'g': '（', 'b': '）',
    's': '『', 'x': '』', 't': '・', 'a': '……', 'z': '――',
}
rows = []
for kana, combos in d.items():
    for c in combos:
        keys = ''.join(' ' if k == 'SPACE' else k for k in sorted(c, key=lambda k: (k != 'SPACE', k)))
        rows.append((keys, kana))
for k, s in symbols.items():
    rows.append((''.join(sorted('jk' + k)), s))
rows.append((' v', '、'))
rows.append((' m', '。'))
seen = {}
for keys, out in rows:
    key = frozenset(keys)
    assert key not in seen or seen[key] == out, (keys, out)
    seen[key] = out
print('// Generated by scripts/gen_naginata_table.py -- do not edit by hand.')
print('// Naginata v18 per eswai/zmk-naginata (reference table; keymap draft')
print('// /data/ashwell/life/keyboard-layouts/scoring/keymaps/naginata_corne/BUILD.md; revision pin 6d852bf9b4).')
print('// Key " " = thumb Space shift. Not independently verified against the official site.')
print('public enum NaginataTable {')
print('    public static let entries: [(keys: String, output: String)] = [')
for keys, out in rows:
    print('        (%s, %s),' % (json.dumps(keys), json.dumps(out, ensure_ascii=False)))
print('    ]')
print('}')
