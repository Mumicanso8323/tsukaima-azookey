    typealias Pair = (String, String)

    private static func build() -> [TsukaimaImeDict.Word] {
        var out: [TsukaimaImeDict.Word] = []
        var seen = Set<String>()
        func add(_ pairs: [Pair], hint: String?) {
            for (reading, word) in pairs {
                let key = reading + "\t" + word
                guard seen.insert(key).inserted else { continue }
                out.append(.init(word: word, reading: reading, hint: hint))
            }
        }
        add(cocSkills, hint: nil)
        add(cocRules, hint: nil)
        add(cocSpells, hint: nil)
        add(cocDeities, hint: "固有名詞")
        add(cocCreatures, hint: "固有名詞")
        add(cocPlaces, hint: "固有名詞")
        add(cocPeople, hint: "人名")
        add(cocBooks, hint: "固有名詞")
        add(cocPhrases, hint: nil)
        add(nechronicaTerms, hint: nil)
        add(nechronicaClasses, hint: "固有名詞")
        add(trpgGeneral, hint: nil)
        add(trpgSystems, hint: "固有名詞")
        add(trpgTools, hint: "固有名詞")
        add(diceNotation, hint: nil)
        return out
    }

